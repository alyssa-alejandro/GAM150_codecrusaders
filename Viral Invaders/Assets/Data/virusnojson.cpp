virus* spawnVirus(int type, float x, float y, std::vector<virus*>& virus_List) {
    virus* new_Virus = new virus;
    if (!new_Virus) return nullptr;

    // Apply saved base stats + any previous upgrades from `saved_Virus_Stats`
    new_Virus->basehp = saved_Virus_Stats[type].basehp;
    new_Virus->currenthp = new_Virus->basehp; // Start at full HP
    new_Virus->dmg = saved_Virus_Stats[type].dmg;
    new_Virus->ms = saved_Virus_Stats[type].ms;
    new_Virus->original_ms = new_Virus->ms;
    new_Virus->currentms = new_Virus->ms;

    // Initialize general virus properties
    new_Virus->x = x;
    new_Virus->y = y;
    new_Virus->indexing = globalindex++;
    new_Virus->radius = 110.0f;
    new_Virus->state = true;
    new_Virus->attackstate = false;
    new_Virus->atkcd = 0.0f;
    new_Virus->virus_bullet.bullet_movement_speed = 5.0f;
    new_Virus->virus_bullet.bullet_radius = 5.0f;
    new_Virus->virus_bullet.start_X = x;
    new_Virus->virus_bullet.start_Y = y;
    new_Virus->type = type;
    new_Virus->ppg_effect = false;


    //  Set Type-Specific Properties (Base + Upgrades Applied)
    switch (type) {
    case hfmdvirus:
        new_Virus->timer = 0.0f;
        new_Virus->color = 0xFFB88227; // Brown
        new_Virus->attacker = false;
        new_Virus->type = hfmdvirus;
        break;
    case chickenpox:
        new_Virus->color = 0xFF7D0F79; // Purple
        new_Virus->attacker = false;
        break;
    case dengue:
        new_Virus->color = 0xFFB52407; // Red
        new_Virus->attackradius = 150.f;
        new_Virus->attacker = true;
        break;
    case shingle:
        new_Virus->color = 0xFFD4BAD3; // Light Purple
        new_Virus->attackradius = 150.f;
        new_Virus->attacker = true;
        break;
    case polio_virus:
        new_Virus->color = 0xADD8E600; // Yellow for polio
        new_Virus->attackradius = 100.f;
        new_Virus->polio_virus.spawn_time_interval = 100.0f; //time interval for spawning minion polio
        new_Virus->polio_virus.generate_time_interval = 150.0f; //time interval for generate gameplay resource
        //num gameplay resource generated by polio when resource generation timer == 0
        new_Virus->polio_virus.generate_resource = 50;
        new_Virus->attacker = false;
        break;
    case minion_polio_virus:
        new_Virus->basehp = 100;
        new_Virus->currenthp = 100;
        new_Virus->dmg = 5;
        new_Virus->ms = 15.0f;
        new_Virus->original_ms = 15.0f;
        new_Virus->currentms = 15.0f;
        new_Virus->color = 0x4B0082FF; // green Color for minion polio
        new_Virus->minion_polio_virus.generate_time_interval = 200.0f; //time interval for generate gameplay resource
        //num gameplay resource generated by minion polio when resource generation timer == 0
        new_Virus->minion_polio_virus.generate_resource = 25;
        new_Virus->attacker = false;
        break;
    case ebola:
        new_Virus->color = 0xFFFF00FF; // Light Purple
        new_Virus->attackradius = 350.f;
        new_Virus->radius = 250.0f;
        new_Virus->attacker = true;
        break;
    default:
        new_Virus->color = 0xFF808080; // Gray (Default for unknown types)
        break;
    }


    Create_Rectangle(
        &new_Virus->mesh,
        new_Virus->radius,
        new_Virus->radius,
        0xFFFFFF00,
        &new_Virus->transform,
        3.0f, 3.0f,
        new_Virus->x,
        new_Virus->y);



    // Create HP bar only for newly spawned virus
    make_hp(virus_List.size(), new_Virus->x, new_Virus->y - 60, 5.0f, true);

    // Add new virus to the list
    virus_List.push_back(new_Virus);



    return new_Virus;
}




void update_Enemies(std::vector<virus*>& spawned_Virus, f64 dt, float targetx, float targety,
    AEMtx33* transforms, AEMtx33* scale, AEMtx33* rotate, AEMtx33* translate,
     float scalex, float scaley, int& meter, int *resources)
{
    for (size_t i = 0; i < spawned_Virus.size(); ++i) {
        virus* current_Virus = spawned_Virus[i];
    
      
        
        // virus
        if (current_Virus->state) {
            // **Render Virus**
            render(scale, rotate, translate, &transforms[0], scalex, scaley, current_Virus->x, current_Virus->y);

            if (current_Virus->type == ebola) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(ebola_Texture, 0, 0);
            }
            if (current_Virus->type == hfmdvirus) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(hfmd_texture, 0, 0);
            }
            if (current_Virus->type == polio_virus) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(polio_texture, 0, 0);
            }
            if (current_Virus->type == minion_polio_virus) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(polio_texture, 0, 0);
            }
            if (current_Virus->type == dengue) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(dengue_texture, 0, 0);
            }
            if (current_Virus->type == shingle) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(shingles_texture, 0, 0);
            }
            if (current_Virus->type == chickenpox) {
                //  Ensure Color Mode is enabled
                AEGfxSetRenderMode(AE_GFX_RM_TEXTURE);
                AEGfxTextureSet(chickenpox_texture, 0, 0);
            }
            AEGfxSetColorToMultiply(1.0f, 1.0f, 1.0f, 1.0f);

            AEGfxSetTransform(transforms->m);
            AEGfxMeshDraw(current_Virus->mesh, AE_GFX_MDM_TRIANGLES);

            AEGfxSetRenderMode(AE_GFX_RM_COLOR);
             
     

            // **Movement Logic**
            if (current_Virus->attackstate == false) {
                current_Virus->x += static_cast<float>(current_Virus->ms * dt);
            }

            // hp bar
            float virusHPPercentage = static_cast<float>(current_Virus->currenthp) / static_cast<float>(current_Virus->basehp);


            if (current_Virus->currenthp >= 0) {
                update_hp_V(current_Virus->indexing, virusHPPercentage, static_cast<float>(dt), spawned_Virus[i]->x, spawned_Virus[i]->y);

            }


            // **Check if Chickenpox Virus is Defeated**
            if (current_Virus->type == chickenpox && (current_Virus->currenthp <= 0 || current_Virus->state ==false)) {
                chickenpox_Defeated = true; // Flag that Chickenpox has been defeated
            }

            // if the current virus is polio, update the polio behaviour here
            if (current_Virus->type == polio_virus) {
                Polio_Behaviour(current_Virus, dt, resources);
            }

            // if the current virus is minion polio, update the minion polio behaviour here
            if (current_Virus->type == minion_polio_virus) {
                Minion_Polio_Behaviour(current_Virus, dt, resources);
            }

            //HFMD 
            if (current_Virus->type == hfmdvirus && current_Virus->state == true) {
                current_Virus->timer += static_cast<float>(dt);
                if (current_Virus->timer >= 3.0f) {
                    *resources += 50;
                    current_Virus->timer = 0.0f;
                 
                }
                
            }

            // **Virus Reaches Target (e.g., Player Base)**
            if (is_circle_intersecting_rectangle(current_Virus->x, current_Virus->y, 50.0f, targetx, targety, 200.0f, 200.0f)) {
                meter += current_Virus->dmg/10;
                current_Virus->currenthp = 0;
                
                if (current_Virus->type == chickenpox) {
                    chickenpox_Defeated = true;
                }
                if (meter >= 100) {
                    level_end = vic;
                }
            }
        }
    }
    spawned_Viruses.erase(
        std::remove_if(spawned_Virus.begin(), spawned_Virus.end(),
            [](virus* v) {
                if (v->currenthp <= 0 || v->state == false) {
                    AEGfxMeshFree(v->mesh);
                    delete v; // Free memory
                    return true;
                }
                return false;
            }),
        spawned_Virus.end()
    );
}




