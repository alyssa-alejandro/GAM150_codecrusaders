struct virus_bullet {
	float start_X = {};//Set to the x position of the virus
	float start_Y = {};//Set to the x position of the virus
	float bullet_radius = 20.f;// t radius for the bullets of the virus
	float bullet_movement_speed = 2.5f;//Sets movement speed of the bullets of the virus
	int targeted_virus_index = -1; //Targetting index of the virus
};
extern struct bullet bullet;

struct DoT_Status {
	bool active = false;   // Is the tower currently taking DoT?
	float duration = 3.0f; // Duration of the effect in seconds
	float timeElapsed = {}; // Time that has passed since DoT started
	int totalDamage = {};   // Total damage to apply over time
};

struct virus {
	int indexing;//Indexing for the virus
	int basehp;//base hp, to be used for hpbar
	int currenthp;//current hp to be used for taking damage
	int dmg;//increases virulence meter/damage to tower
	unsigned int color;//sets the color of the virus and the color of the bullets
	float x;//x coords of the virus
	float y;//y coords of the virus
	float radius;//radius/size of the virus
	float attackradius;//attack radius of the virus
	float ms, original_ms; //movement speed
	AEGfxTexture* texture;
	float timer;
	float atkcd;
	float currentms;//current movement speed of the virus
	int type; //type as stated in enums
	bool state; //default false, true when spawned
	bool attacker; //set to false for sprites that cannot attack
	bool attackstate; //set to false for all none attackers
	float spawnx;//x coords where the virus spawns
	float spawny;//y coords when the virus dspawn
	AEGfxVertexList* mesh;   // Mesh for rendering the virus
	bool ppg_effect;			// indication of whether virus is under ppg effect
	time_t start_time, current_time, elapsed_time, time_before_death;			// used for macrophage
	AEMtx33 transform;       // Transformation matrix for rendering
	struct virus_bullet virus_bullet; //virus should have their own bullet 

	struct polio polio_virus; //include polio struct
	struct polio minion_polio_virus; //include minion polio struct

	DoT_Status DOT; // DOT damage type
};


